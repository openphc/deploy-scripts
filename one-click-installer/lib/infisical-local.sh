#!/usr/bin/env bash
# one-click-installer/lib/infisical-local.sh <up|down|status|reset> — a LOCAL, self-contained Infisical for the one-click installer.
#
#   sudo bash one-click-installer/lib/infisical-local.sh up        # start it, create a first org-admin, write admin.env
#   sudo bash one-click-installer/lib/infisical-local.sh status
#   sudo bash one-click-installer/lib/infisical-local.sh down      # stop (data kept)
#   sudo bash one-click-installer/lib/infisical-local.sh reset     # stop and DELETE all its data
#
# WHY: one-click-installer/install.sh creates a project + machine identity in an Infisical instance using an ORG-ADMIN login
# (a project-scoped identity structurally cannot create a project). Documented use is the central instance, reached over
# an SSH tunnel. On a brand-new machine — a trial, a demo, an air-gapped site — there is no such instance, and the installer
# used to fail at step 1 with no way forward. This stands one up on localhost:8080 (127.0.0.1 only — never published
# to the network), which is exactly the INFISICAL_DOMAIN default the installer already uses, so nothing else changes.
#
# Image defaults to the exact digest the reference deployment runs (the installer's REST sequence was verified against it); override with
# INFISICAL_IMAGE. Everything lives in $CCE_LOCAL_INFISICAL_DIR (default /opt/cce-local-infisical, 0700):
#   .env (generated secrets, 0600)   docker-compose.yml   admin.env (INFISICAL_ADMIN_EMAIL/PASSWORD, 0600)
#
# The installer then picks the admin login up from the environment:
#   sudo bash -c '. /opt/cce-local-infisical/admin.env && export INFISICAL_ADMIN_EMAIL INFISICAL_ADMIN_PASSWORD && bash one-click-installer/install.sh'
# (one-click-install.sh does this itself when it finds admin.env and no explicit credentials.)
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$HERE/sudo-compat.sh"
CMD="${1:-status}"
STATE="${CCE_LOCAL_INFISICAL_DIR:-/opt/cce-local-infisical}"
IMAGE="${INFISICAL_IMAGE:-infisical/infisical@sha256:6fb7116d8976f6835af89d8a76806a7c219b69d251107d9bbcf7e1e8b11299c7}"
BASE="http://127.0.0.1:8080"
[ "$(id -u)" = 0 ] || { echo "run as root: sudo bash $0 $CMD" >&2; exit 1; }
log() { echo "[infisical-local] $*"; }

ensure_docker() {
  if ! command -v docker >/dev/null 2>&1 || ! docker compose version >/dev/null 2>&1; then
    log "installing docker + compose plugin (needed only to run this local Infisical)…"
    DEBIAN_FRONTEND=noninteractive apt-get update -qq
    DEBIAN_FRONTEND=noninteractive apt-get install -y -qq docker.io docker-compose-v2 >/dev/null
    systemctl enable --now docker >/dev/null 2>&1
  fi
}
dc() { docker compose --project-name cce-local-infisical --project-directory "$STATE" "$@"; }
healthy() { curl -sf --max-time 5 "$BASE/api/status" >/dev/null 2>&1; }

case "$CMD" in
  status)
    if healthy; then echo "local Infisical: UP at $BASE"; [ -f "$STATE/admin.env" ] && echo "admin login: $STATE/admin.env" || echo "no admin yet — run: up"
    else echo "local Infisical: DOWN"; fi ;;
  down)  dc down; log "stopped (data kept in $STATE)";;
  reset) dc down -v 2>/dev/null || true; rm -rf "$STATE"; log "removed $STATE and its volumes";;
  up)
    ensure_docker
    install -d -m 700 "$STATE"
    if [ ! -f "$STATE/.env" ]; then
      umask 077
      { echo "ENCRYPTION_KEY=$(openssl rand -hex 16)"
        echo "AUTH_SECRET=$(openssl rand -base64 32)"
        echo "PG_PASSWORD=$(openssl rand -hex 16)"; } > "$STATE/.env"
      log "generated secrets -> $STATE/.env (0600)"
    fi
    cat > "$STATE/docker-compose.yml" <<YML
# generated by one-click-installer/lib/infisical-local.sh — do not edit; re-run 'up' to regenerate
services:
  db:
    image: postgres:14-alpine
    restart: unless-stopped
    environment:
      POSTGRES_USER: infisical
      POSTGRES_DB: infisical
      POSTGRES_PASSWORD: \${PG_PASSWORD}
    volumes: [pgdata:/var/lib/postgresql/data]
    healthcheck: {test: ["CMD-SHELL", "pg_isready -U infisical"], interval: 5s, timeout: 3s, retries: 20}
  redis:
    image: redis:7-alpine
    restart: unless-stopped
  backend:
    image: ${IMAGE}
    restart: unless-stopped
    depends_on: {db: {condition: service_healthy}, redis: {condition: service_started}}
    ports: ["127.0.0.1:8080:8080"]          # loopback only — never reachable from the network
    environment:
      SITE_URL: http://localhost:8080
      TELEMETRY_ENABLED: "false"
      ENCRYPTION_KEY: \${ENCRYPTION_KEY}
      AUTH_SECRET: \${AUTH_SECRET}
      DB_CONNECTION_URI: postgres://infisical:\${PG_PASSWORD}@db:5432/infisical
      REDIS_URL: redis://redis:6379
volumes: {pgdata: {}}
YML
    dc up -d
    log "waiting for Infisical to answer on $BASE (first start runs DB migrations, can take a minute or two)…"
    for _ in $(seq 1 90); do healthy && break; sleep 4; done
    healthy || { echo "ERROR: Infisical did not become healthy — docker compose -p cce-local-infisical logs backend" >&2; exit 1; }
    log "up."
    if [ ! -f "$STATE/admin.env" ]; then
      EMAIL="admin@cce-local.invalid"; PASS="$(openssl rand -base64 24 | tr -d '/+=' | head -c 28)Aa1!"
      code="$(curl -s -o "$STATE/.signup.json" -w '%{http_code}' -X POST "$BASE/api/v1/admin/signup" -H 'Content-Type: application/json' \
              -d "{\"email\":\"$EMAIL\",\"password\":\"$PASS\",\"firstName\":\"CCE\",\"lastName\":\"Admin\"}")"
      if [ "$code" = 200 ]; then
        umask 077; printf 'INFISICAL_ADMIN_EMAIL=%s\nINFISICAL_ADMIN_PASSWORD=%s\nINFISICAL_DOMAIN=%s\n' "$EMAIL" "$PASS" "$BASE" > "$STATE/admin.env"
        rm -f "$STATE/.signup.json"; log "created first org-admin -> $STATE/admin.env (0600)"
      else
        echo "ERROR: first-admin signup returned HTTP $code: $(head -c 300 "$STATE/.signup.json")" >&2
        echo "       If an admin already exists from an earlier run, restore $STATE/admin.env or run: reset" >&2; exit 1
      fi
    else log "admin already created ($STATE/admin.env)"; fi ;;
  *) echo "usage: $0 <up|down|status|reset>" >&2; exit 2;;
esac
